function history=radio_history_init(cfg)
%RADIO_HISTORY_INIT Joint errors: [persistent range bias; clock estimate error;
% stored range errors]. Clock error is estimate minus current true ratio.
history=struct('P',diag([cfg.ranging.device_persistent_bias_std_m^2, ...
    (cfg.ranging.initial_clock_ratio_std_ppm*1e-6)^2]), ...
    'kappa',NaN,'calibration_time_s',-Inf,'time_s',0,'ranges_m',[], ...
    'times_s',[],'kinds',{{}},'last_id',0);
end
