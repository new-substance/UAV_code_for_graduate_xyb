function plan=reference_return_plan(nav,cfg,current_reference,blocked)
%REFERENCE_RETURN_PLAN Mapped-reference graph and conditional time reserve.
% Future visual success is a condition, never a fictitious posterior update.
if nargin<4,blocked=[];end
xy=cfg.scene.reference_centers_xy_m;home=cfg.scene.home_xyz_m(:);
[~,goal]=min(vecnorm(xy-home(1:2)',2,2));
path=uavmvp.reference_path(cfg,current_reference,goal,blocked);ids=path.ids;
first=uavmvp.predict_leg(nav,[xy(current_reference,:)';cfg.scene.flight_height_m],cfg,60,current_reference);
plan=struct('available',path.available && first.arrived && ...
    first.envelope_inside_area && first.reference.envelope_inside, ...
    'reference_ids',ids,'first_leg',first,'conditional_future_reference_success',true, ...
    'reserve_s',first.duration_s+2+path.time_proxy_s+ ...
        numel(ids)*cfg.navigation_candidate.reference_observation_s*cfg.navigation_candidate.reference_max_attempts_per_visit+ ...
        cfg.sim.landing_reserve_s+cfg.motion_and_budget.return_reserve_s);
end
