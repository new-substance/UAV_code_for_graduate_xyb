function plan=departure_repair_plan(nav,reference_id,cfg,deadline)
%DEPARTURE_REPAIR_PLAN One real departure reacquisition with conditional reserve.
% Match visit_reference's movement allowance and frame count. Propagate the
% whole allowance without crediting an image, then reserve the mapped return.
nav=uavmvp.nav_prune(nav,[]);
target=[cfg.scene.reference_centers_xy_m(reference_id,:)';cfg.scene.flight_height_m];
flight=uavmvp.predict_leg(nav,target,cfg,60,reference_id);
frames=cfg.navigation_candidate.reference_max_attempts_per_visit* ...
    cfg.navigation_candidate.reference_observation_s;
movement_allowance=flight.duration_s+2;
after=uavmvp.predict_hold(flight.nav,2+frames,cfg);
back=uavmvp.reference_return_plan(after.nav,cfg,reference_id);
observation_deadline=deadline-back.reserve_s;
observation_end=nav.t+movement_allowance+frames;
reason='DEPARTURE_REPAIR_ADMISSIBLE';
if ~flight.arrived || ~flight.envelope_inside_area || ~flight.reference.envelope_inside
    reason='DEPARTURE_REPAIR_NAVIGATION_REJECTED';
elseif ~isfinite(back.reserve_s) || observation_end>observation_deadline
    reason='DEPARTURE_REPAIR_RETURN_BUDGET';
end
plan=struct('accepted',strcmp(reason,'DEPARTURE_REPAIR_ADMISSIBLE'),'reason',reason, ...
    'reference_id',reference_id,'start_s',nav.t,'flight_duration_s',flight.duration_s, ...
    'movement_allowance_s',movement_allowance,'frame_allowance_s',frames, ...
    'observation_end_bound_s',observation_end,'return_reserve_s',back.reserve_s, ...
    'observation_deadline_s',observation_deadline,'deadline_s',deadline, ...
    'slack_s',observation_deadline-observation_end,'arrived',flight.arrived, ...
    'envelope_inside_area',flight.envelope_inside_area, ...
    'reference_envelope_inside',flight.reference.envelope_inside, ...
    'uncorrected_return_available',back.available, ...
    'conditional_future_reference_success',true,'prediction_version',after.nav.version);
end
