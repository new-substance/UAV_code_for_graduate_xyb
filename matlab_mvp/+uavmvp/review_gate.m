function review=review_gate()
%REVIEW_GATE Exact specification/config/source release identity before flight.
main=fileparts(fileparts(mfilename('fullpath')));repo=fileparts(main);
review=jsondecode(fileread(fullfile(repo,'research_configs','review.json')));
assert(review.mission_enabled,'uavproject:SimulationNotApproved', ...
    'Complete the scoped task integration review before starting a mission.');
now=uavmvp.project_fingerprints();
assert(strcmp(now.specification,review.specification_sha256) && ...
    strcmp(now.configuration,review.configuration_sha256) && ...
    isfield(review,'source_sha256') && strcmp(now.source,review.source_sha256), ...
    'uavproject:ReviewMismatch','Release review does not match current specification/config/source bytes.');
assert(strcmp(review.status,'approved_for_bounded_development'), ...
    'uavproject:ReviewScope','Only the explicitly reviewed development scope is implemented.');
end
