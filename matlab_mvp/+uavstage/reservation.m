function r=reservation(cfg)
t=uavmvp.radio_timing(cfg,1);
group=t.group_s+cfg.css.wake_ready_s+t.frames.identity+cfg.css.guard_s;
n=cfg.stage.transaction_attempt_cap;
extra=0;if isfield(cfg.stage,'extra_service_delay_s'),extra=cfg.stage.extra_service_delay_s;end
r=struct('settle_s',cfg.motion_and_budget.settle_s,'extra_service_s',extra, ...
    'group_each_s',group,'cold_each_max_s',t.cold_max_s, ...
    'attempt_count',n,'backoff_s',max(0,n-1)*cfg.stage.backoff_s, ...
    'compute_s',cfg.stage.compute_reserve_s, ...
    'stop_s',cfg.planner.stop_notice_attempt_cap*max(t.stop_success_s,cfg.css.exchange_deadline_s), ...
    'margin_s',cfg.stage.reserve_margin_s);
r.total_s=r.settle_s+extra+n*(group+t.cold_max_s)+r.backoff_s+r.compute_s+r.stop_s+r.margin_s;
r.radio_window_s=r.settle_s+extra+n*(group+t.cold_max_s)+r.backoff_s+r.margin_s;
r.post_radio_reference_s=cfg.navigation_candidate.reference_max_attempts_per_visit* ...
    cfg.navigation_candidate.reference_observation_s;
end
