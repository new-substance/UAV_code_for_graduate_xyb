function gate=navigation_gate(nav,duration,cfg)
pred=uavmvp.predict_hold(nav,duration,cfg);
scale=cfg.stage.navigation_covariance_scale;
radius=sqrt(cfg.stage.local_geometry_level*max(eig(pred.nav.P(1:2,1:2)*scale)));
age=pred.nav.t-nav.last_reference_time_s;
current_age=nav.t-nav.last_reference_time_s;
gate=struct('accepted',radius<=cfg.stage.navigation_radius_limit_m && ...
    current_age<=cfg.stage.navigation_max_reference_age_s && pred.envelope_inside_area, ...
    'predicted_radius_m',radius,'predicted_reference_age_s',age, ...
    'current_reference_age_s',current_age, ...
    'duration_s',duration,'inside_area',pred.envelope_inside_area, ...
    'nav_version',nav.version,'covariance_scale',scale);
end
